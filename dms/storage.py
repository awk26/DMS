"""File storage abstraction.

All stored content is addressed by an opaque *storage key* generated by the
application (never derived from user input). ``LocalStorage`` maps keys onto a
directory; a different backend (network share, object storage) only needs to
implement the same small interface.

When a key ring is supplied, content is encrypted at rest (AES-256-GCM, see
``crypto.py``). Sizes and SHA-256 digests always describe the *plaintext*, and
reads always return the exact original bytes. Files written before encryption
was enabled are still readable and can be converted with ``flask encrypt-storage``.
"""
import hashlib
import io
import os
import re
import uuid
from contextlib import contextmanager
from pathlib import Path

from .crypto import CryptoError, DecryptingReader, encrypt_stream, is_encrypted, rewrap_file

_KEY_RE = re.compile(r"^[a-z]+(/[A-Za-z0-9_.-]+)+$")
CHUNK = 1024 * 1024


class StorageError(Exception):
    pass


class _PlainReader(io.BufferedReader):
    """Plain (legacy, unencrypted) file with a ``size`` attribute like DecryptingReader."""

    @property
    def size(self):
        return os.fstat(self.fileno()).st_size


class LocalStorage:
    def __init__(self, root, key_ring=None):
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)
        self.ring = key_ring

    @property
    def encrypted(self):
        return self.ring is not None

    # -- key helpers -----------------------------------------------------------------
    @staticmethod
    def new_document_key():
        u = uuid.uuid4().hex
        return f"documents/{u[:2]}/{u[2:4]}/{u}"

    def _path(self, key):
        if not key or not _KEY_RE.match(key) or ".." in key.split("/"):
            raise StorageError("Invalid storage key")
        path = (self.root / key).resolve()
        if self.root not in path.parents:
            raise StorageError("Invalid storage key")
        return path

    # -- operations ------------------------------------------------------------------
    def save_stream(self, key, stream):
        """Write a stream atomically (encrypted when enabled). Returns (size, sha256) of the plaintext."""
        path = self._path(key)
        if path.exists():
            raise StorageError("Storage key already exists")
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_name(f".{path.name}.{uuid.uuid4().hex}.tmp")
        digest, counter = hashlib.sha256(), [0]

        def seen(chunk):
            digest.update(chunk)
            counter[0] += len(chunk)

        try:
            with open(tmp, "xb") as out:
                if self.ring is not None:
                    encrypt_stream(self.ring, stream, out, on_plain=seen)
                else:
                    for chunk in iter(lambda: stream.read(CHUNK), b""):
                        seen(chunk)
                        out.write(chunk)
                out.flush()
                os.fsync(out.fileno())
            os.replace(tmp, path)
        except BaseException:
            tmp.unlink(missing_ok=True)
            raise
        return counter[0], digest.hexdigest()

    def save_bytes(self, key, data, overwrite=False):
        """Write bytes atomically. With overwrite=True a leftover file (e.g. from an interrupted import) is replaced."""
        path = self._path(key)
        if path.exists():
            if overwrite:
                path.unlink()
            else:
                raise StorageError("Storage key already exists")
        return self.save_stream(key, io.BytesIO(data))

    def open_reader(self, key):
        """A seekable binary reader of the plaintext with a ``size`` attribute. Caller closes it."""
        fh = open(self._path(key), "rb", buffering=0)
        try:
            if is_encrypted(fh):
                if self.ring is None:
                    raise StorageError("File is encrypted but no key ring is configured")
                return DecryptingReader(fh, self.ring)
            return _PlainReader(fh, CHUNK)
        except CryptoError as exc:
            fh.close()
            raise StorageError(str(exc)) from exc
        except BaseException:
            fh.close()
            raise

    @contextmanager
    def open(self, key):
        reader = self.open_reader(key)
        try:
            yield reader
        finally:
            reader.close()

    def read_bytes(self, key):
        with self.open(key) as fh:
            return fh.read()

    def size(self, key):
        with self.open(key) as fh:
            return fh.size

    def exists(self, key):
        try:
            return self._path(key).is_file()
        except StorageError:
            return False

    def delete(self, key):
        try:
            self._path(key).unlink(missing_ok=True)
        except StorageError:
            pass

    def local_path(self, key):
        """Filesystem path of the stored (possibly encrypted) file. Never serve this directly."""
        return self._path(key)

    def sha256(self, key):
        digest = hashlib.sha256()
        try:
            with self.open(key) as fh:
                for chunk in iter(lambda: fh.read(CHUNK), b""):
                    digest.update(chunk)
        except (StorageError, CryptoError):
            return None
        return digest.hexdigest()

    def is_encrypted_at_rest(self, key):
        with open(self._path(key), "rb") as fh:
            return is_encrypted(fh)

    # -- maintenance -------------------------------------------------------------------
    def iter_keys(self):
        for path in self.root.rglob("*"):
            if path.is_file() and not path.name.startswith("."):
                rel = path.relative_to(self.root).as_posix()
                if _KEY_RE.match(rel):
                    yield rel

    def encrypt_existing(self, key):
        """Encrypt a legacy plaintext file in place (atomic). Returns True when converted."""
        if self.ring is None:
            raise StorageError("Encryption is not configured")
        path = self._path(key)
        with open(path, "rb") as fh:
            if is_encrypted(fh):
                return False
            tmp = path.with_name(f".{path.name}.{uuid.uuid4().hex}.tmp")
            try:
                with open(tmp, "xb") as out:
                    encrypt_stream(self.ring, fh, out)
                    out.flush()
                    os.fsync(out.fileno())
            except BaseException:
                tmp.unlink(missing_ok=True)
                raise
        os.replace(tmp, path)
        return True

    def rewrap(self, key):
        if self.ring is None:
            return False
        return rewrap_file(self._path(key), self.ring)


def get_storage():
    from flask import current_app
    return current_app.extensions["dms_storage"]
